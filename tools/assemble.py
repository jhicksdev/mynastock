#!/usr/bin/env python3
"""Concatenate the portable modules into one file the JS target can compile.

myna 0.4.1 emits extensionless relative specifiers for `-t js`, so a multi-file
portable program cannot be loaded as ES modules. This tool is the temporary bridge:
it strips module headers and relative imports, preserves source order, and refuses
duplicate top-level names. Delete it when upstream JS bundling lands (Myna D-002).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LISTED = [
    line.strip()
    for line in (ROOT / "tools/portable.txt").read_text(encoding="utf-8").splitlines()
    if line.strip()
]
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build/js/portable.myna"

DECLARATION = re.compile(r"^(\+?@\w+|\+?\$\$?\w+|[A-Z][A-Z0-9_]*)\s*[={(<:-]")
TARGET_HEADER = re.compile(r"^\s*@target\(")
IMPORT = re.compile(r"^\s*<")

parts = [
    "# Generated by tools/assemble.py from tools/portable.txt. Do not edit by hand.",
    "@target(js)",
    "",
]
seen: dict[str, str] = {}

for rel in LISTED:
    path = ROOT / rel
    parts.append(f"# ---- {rel} ----")
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if TARGET_HEADER.match(line) or IMPORT.match(line):
            continue
        match = DECLARATION.match(line)
        if match:
            name = match.group(1).lstrip("+$@")
            if name in seen and seen[name] != rel:
                sys.exit(f"duplicate top-level name {name!r}: {seen[name]} and {rel}:{lineno}")
            seen[name] = rel
        parts.append(line)
    parts.append("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(parts), encoding="utf-8")
print(f"assembled {len(LISTED)} modules -> {OUT}")
