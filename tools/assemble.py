#!/usr/bin/env python3
"""Concatenate the portable modules into one file the JS target can compile.

myna 0.4.x rejects relative imports for `-t js` and cannot bundle them, so a
multi-file portable program cannot be compiled as-is. This tool is the temporary
bridge: it strips module headers and relative imports, preserves source order, and
refuses duplicate top-level names. Delete it when upstream JS bundling lands (D-002).

Usage:
    tools/assemble.py [OUT] [--extra MANIFEST]
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECLARATION = re.compile(r"^(\+?@\w+|\+?\$\$?\w+|[A-Z][A-Z0-9_]*)\s*[={(<:-]")
TARGET_HEADER = re.compile(r"^\s*@target\(")
IMPORT = re.compile(r"^<")


def read_manifest(path: Path) -> list[str]:
    return [
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("out", nargs="?", default=str(ROOT / "build/js/portable.myna"))
    parser.add_argument("--extra", help="additional manifest, appended after portable.txt")
    args = parser.parse_args()

    listed = read_manifest(ROOT / "tools/portable.txt")
    if args.extra:
        listed += read_manifest(ROOT / args.extra)

    seen: dict[str, str] = {}
    parts = [
        "# Generated by tools/assemble.py. Do not edit by hand.",
        "@target(js)",
        "",
    ]
    for rel in listed:
        path = ROOT / rel
        parts.append(f"# ---- {rel} ----")
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if TARGET_HEADER.match(line) or IMPORT.match(line):
                continue
            match = DECLARATION.match(line)
            if match:
                name = match.group(1).lstrip("+$@")
                if name in seen and seen[name] != rel:
                    sys.exit(f"duplicate top-level name {name!r}: {seen[name]} and {rel}:{lineno}")
                seen[name] = rel
            parts.append(line)
        parts.append("")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"assembled {len(listed)} modules -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
